//! Emits the three OPL2 constant tables from their closed-form definitions.
//!
//! Every table the chip needs is a published closed-form function of its
//! index, so none of them has to be transcribed from another implementation.
//! `src/synth.rs` carries the emitted arrays, and its tests regenerate them
//! from these same expressions in `f64` and assert equality, so the derivation is
//! re-proved on every test run rather than asserted in a comment.
//!
//! Run with `cargo run -p gp64-opl2 --example gen_opl2_tables`.

use std::f64::consts::PI;

/// Log-sin ROM: the first quarter of a sine in the log domain.
///
/// Attenuation is expressed in units of 1/256 of an octave of amplitude, so a
/// value of 256 halves the amplitude.
fn log_sin(index: usize) -> u16 {
    let angle = (index as f64 + 0.5) * PI / 512.0;
    (-angle.sin().log2() * 256.0).round() as u16
}

/// Exponent ROM: the mantissa of `2^-x` over one octave, scaled by 1024.
///
/// The index runs backwards so that a larger attenuation gives a smaller
/// value, which is what lets the caller finish the conversion with one shift.
fn exponent(index: usize) -> u16 {
    (2.0_f64.powf((255 - index) as f64 / 256.0) * 1024.0).round() as u16
}

/// Key-scale-level ROM: attenuation against the top of the F-number range.
///
/// One unit is 0.75 dB and one octave of F-number is eight units, which is the
/// 6 dB per octave of the steepest key-scale setting.
fn key_scale_level(index: usize) -> u8 {
    if index == 0 {
        return 0;
    }
    ((8.0 * (index as f64).log2()).ceil() as u8) + 32
}

fn emit_u16(name: &str, len: usize, per_row: usize, f: impl Fn(usize) -> u16) {
    println!("#[rustfmt::skip]");
    println!("static {name}: [u16; {len}] = [");
    for row in (0..len).step_by(per_row) {
        let cells: Vec<String> = (row..(row + per_row).min(len))
            .map(|index| format!("0x{:03x},", f(index)))
            .collect();
        println!("    {}", cells.join(" "));
    }
    println!("];");
}

fn main() {
    println!("// Generated by tools/gen_opl2_tables.rs; do not edit by hand.");
    println!();
    emit_u16("LOG_SIN", 256, 8, log_sin);
    println!();
    emit_u16("EXPONENT", 256, 8, exponent);
    println!();
    println!("#[rustfmt::skip]");
    println!("static KEY_SCALE_LEVEL: [u8; 16] = [");
    let cells: Vec<String> = (0..16)
        .map(|index| format!("{},", key_scale_level(index)))
        .collect();
    println!("    {}", cells.join(" "));
    println!("];");
}
